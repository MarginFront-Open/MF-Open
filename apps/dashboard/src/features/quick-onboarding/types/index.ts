export type VerificationStatus = 'waiting' | 'detected' | 'verified' | 'skipped'

// Framework metadata
export interface FrameworkInfo {
  id: Framework
  name: string
  icon: string // Icon component name or emoji
  available: boolean
  description?: string
}

// Language metadata
export interface LanguageInfo {
  id: Language
  name: string
  available: boolean
  fileExtension: string
}

// IDE metadata
export interface IDEInfo {
  id: IDE
  name: string
  icon: string
  promptTemplate: string
}

// Company context generated by AI
export interface CompanyContext {
  shortSummary: string
  longContext: string
}

// Enhanced Preview Types - Toggleable Items
export interface ToggleableItem {
  id: string
  enabled: boolean
}

export interface EnhancedPricingTier extends ToggleableItem {
  name: string
  price: number
  billingCycle: string
  setupFee?: number
  features: string[]
  usageLimits?: Record<string, number | null>
  overageRates?: Record<string, number>
  isPopular?: boolean
  isEnterprise?: boolean
}

export interface EnhancedSignal extends ToggleableItem {
  name: string
  shortName: string
  type: 'usage' | 'volume'
  description?: string
}

export interface EnhancedServiceCost extends ToggleableItem {
  serviceName: string
  provider: string
  unitType: string
  costPerUnit: number
}

export interface EnhancedCustomer extends ToggleableItem {
  name: string
  email: string
  phone?: string
  industry?: string
  employeeCount?: number
  region?: string
  city?: string
  state?: string
  country?: string
  zipCode?: string
  addressLine1?: string
  timezone?: string
  contactName?: string
  contactTitle?: string
  assignedPlan: string
  subscriptionStartDaysAgo?: number
  tags?: string[]
  notes?: string
}

export interface EnhancedPreviewData {
  success: boolean
  websiteUrl: string
  pricingPageUrl?: string | null
  companyInfo: {
    name: string
    description?: string
    logo?: string
    website?: string
  }
  companyContext?: CompanyContext
  pricingData: {
    tiers: EnhancedPricingTier[]
    signals: EnhancedSignal[]
    serviceCosts: EnhancedServiceCost[]
  }
  customers: EnhancedCustomer[]
  summary: {
    pricingTiersCount: number
    signalsCount: number
    serviceCostsCount: number
    customersCount: number
  }
  message?: string
}

// Preview data from website analysis
export interface PreviewData {
  success?: boolean
  companyInfo?: {
    companyName: string
    logoUrl?: string | null
    linkedinUrl?: string | null
    twitterUrl?: string | null
    screenshotUrl?: string | null
  }
  companyContext?: CompanyContext
  billingSetup?: {
    agent?: {
      id?: string
      name: string
      description: string
      agentCode?: string
      isActive?: boolean
    }
    signals?: Array<{
      name: string
      shortName?: string
      type: 'usage' | 'volume'
      description: string
    }>
    pricingPlan?: {
      id?: string
      name: string
      description?: string
      featuresList?: Record<string, string> | string[]
      features?: string[]
      isActive?: boolean
    }
    pricingStrategies?: Array<{
      name: string
      chargeType: string
      billingFrequency?: string
      rate?: number
      pricingModel?: string
      tiers?: Array<{
        lower: number
        upper: number | null
        rate: number
      }>
      signalName?: string
      active?: boolean
    }>
    serviceCosts?: Array<{
      serviceName: string
      provider: string
      unitType?: string
      costPerUnit: number
    }>
  }
  message?: string
}

// Created resources after setup
export interface CreatedResources {
  agent?: {
    id: string
    name: string
  }
  signals?: Array<{
    id: string
    name: string
    shortName?: string
  }>
  pricingPlan?: {
    id: string
    name: string
  }
  serviceCosts?: Array<{
    id: string
    serviceName: string
  }>
  apiKey?: {
    id: string
    token: string
  }
  customer?: {
    id: string
    externalId: string
    name: string
  }
  subscription?: {
    id: string
  }
}

