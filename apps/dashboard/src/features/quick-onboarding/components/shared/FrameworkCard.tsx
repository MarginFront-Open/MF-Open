export const FrameworkCard = ({
  id,
  name,
  selected,
  disabled = false,
  onClick,
}: FrameworkCardProps) => {
  return (
    <button
      onClick={disabled ? undefined : onClick}
      disabled={disabled}
      className={cn(
        'relative flex min-w-[90px] flex-col items-start rounded-lg border p-2.5 transition-all',
        disabled
          ? 'cursor-not-allowed border-border/30 bg-muted/10'
          : selected
            ? 'border-primary/30 bg-primary/10 text-foreground'
            : 'border-border bg-card text-muted-foreground hover:border-primary/30 hover:bg-muted/50 hover:text-foreground'
      )}
    >
      <div className={cn('mb-1.5', disabled && 'opacity-40')}>
        <FrameworkIcon framework={id} />
      </div>
      <span
        className={cn(
          'text-xs font-medium',
          disabled
            ? 'text-muted-foreground/60'
            : selected
              ? 'text-foreground'
              : ''
        )}
      >
        {name}
      </span>
      {disabled && (
        <span className='absolute -right-1.5 -top-1.5 rounded-full border border-border/50 bg-muted px-1.5 py-0.5 text-[9px] font-medium text-muted-foreground'>
          Soon
        </span>
      )}
    </button>
  )
}

