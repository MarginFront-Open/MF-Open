const OK: SchtasksResult = { status: 0, stdout: "", stderr: "" };
const MISSING: SchtasksResult = {
  status: 1,
  stdout: "",
  stderr: "ERROR: The system cannot find the file specified.",
};

function recording(answers: (args: string[]) => SchtasksResult = () => OK) {
  const calls: string[][] = [];
  return {
    calls,
    run: (args: string[]) => {
      calls.push(args);
      return answers(args);
    },
  };
}

// A definition shaped exactly like the one production emits, for the parser tests that
// do not need a real Windows underneath them.
const SAMPLE_XML = renderScheduledTaskXml({
  nodePath: "C:\\Program Files\\nodejs\\node.exe",
  cliPath: "C:\\Users\\dev\\.marginfront-ccc\\cli.js",
  userId: "RUNNERBOX\\dev",
  workingDirectory: "C:\\Users\\dev\\.marginfront-ccc",
  consoleHostPath: "C:\\Windows\\System32\\conhost.exe",
});

// ===========================================================================
// THE DEFINITION WE GENERATE
// ===========================================================================
describe("the task definition", () => {
  test("starts at THIS user's logon and nothing else", () => {
    const parsed = parseScheduledTaskXml(SAMPLE_XML);
    expect(parsed.triggerTypes).toEqual(["LogonTrigger"]);
    expect(parsed.startsAtLogon).toBe(true);
    expect(parsed.logonTriggerUserId).toBe("RUNNERBOX\\dev");
  });

  test("carries restart-on-failure, which covers a launch that fails, not a node crash", () => {
    const parsed = parseScheduledTaskXml(SAMPLE_XML);
    expect(parsed.restartsOnFailure).toBe(true);
    expect(parsed.restartIntervalIso).toBe(TASK_RESTART_INTERVAL);
    expect(parsed.restartCount).toBe(TASK_RESTART_COUNT);
  });

  test("runs as the signed-in user with an interactive token, never elevated", () => {
    const parsed = parseScheduledTaskXml(SAMPLE_XML);
    expect(parsed.runAsUserId).toBe("RUNNERBOX\\dev");
    expect(parsed.logonType).toBe("InteractiveToken");
    expect(parsed.elevated).toBe(false);
    expect(parsed.perUser).toBe(true);
  });

  // The negative control for the assertion above: if `elevated` could not tell an
  // administrator task apart from ours, saying "never elevated" would be decoration.
  test("an elevated task reads back as elevated", () => {
    const xml = SAMPLE_XML.replace(
      "<RunLevel>LeastPrivilege</RunLevel>",
      "<RunLevel>HighestAvailable</RunLevel>",
    );
    expect(parseScheduledTaskXml(xml).elevated).toBe(true);
  });

  // Windows drops every element whose value is the default when it re-serializes a
  // task, and LeastPrivilege IS the default - so the registration we read back has no
  // RunLevel at all. Asserting runLevel === "LeastPrivilege" fails against real
  // Windows output.
  test("an omitted RunLevel means the default, which is not elevated", () => {
    const xml = SAMPLE_XML.replace(
      "      <RunLevel>LeastPrivilege</RunLevel>\n",
      "",
    );
    const parsed = parseScheduledTaskXml(xml);
    expect(parsed.runLevel).toBeNull();
    expect(parsed.elevated).toBe(false);
  });

  // THE THREE DEFAULTS THAT WOULD SILENTLY BREAK THE METER, which these settings
  // avoid. Without them Windows would stop the meter after three days, kill
  // it the moment the laptop was unplugged, and refuse to start it on battery.
  test("has no execution time limit - the default would kill the meter every third day", () => {
    expect(parseScheduledTaskXml(SAMPLE_XML).executionTimeLimit).toBe("PT0S");
  });

  test("keeps running on battery - both battery defaults are true and would stop it", () => {
    expect(SAMPLE_XML).toContain(
      "<DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>",
    );
    expect(SAMPLE_XML).toContain(
      "<StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>",
    );
  });

  // THE NO-WINDOW SHAPE. A console program started by an
  // InteractiveToken task gets a console window on the desktop, and closing it kills
  // the meter. The task therefore starts the headless console host, which creates no
  // window and starts node as its client.
  test("starts the meter behind the headless console host, so it gets no window", () => {
    const parsed = parseScheduledTaskXml(SAMPLE_XML);
    expect(parsed.command).toBe("C:\\Windows\\System32\\conhost.exe");
    expect(parsed.argumentsText).toBe(
      '--headless "C:\\Program Files\\nodejs\\node.exe" "C:\\Users\\dev\\.marginfront-ccc\\cli.js" run --log-to-files',
    );
    expect(parsed.hidesConsoleWindow).toBe(true);
  });

  // WHERE THE METER'S OWN OUTPUT GOES. Behind the headless
  // console host there is no screen, and Task Scheduler captures nothing - the macOS
  // job gets its two log files from launchd, and Windows has no equivalent. So the
  // action has to end in the flag that makes `run` write them itself, or `status`
  // tails two files nobody ever writes.
  test("tells the meter to write its own output to the files status tails", () => {
    const parsed = parseScheduledTaskXml(SAMPLE_XML);
    expect(parsed.argumentsText).toMatch(
      new RegExp(`\\brun ${LOG_TO_FILES_FLAG}$`),
    );
    // The flag is the meter's, so it has to sit after the subcommand rather than
    // among the console host's own arguments, where node would never see it.
    expect(parsed.argumentsText!.indexOf(LOG_TO_FILES_FLAG)).toBeGreaterThan(
      parsed.argumentsText!.indexOf(" run"),
    );
  });

  test("still runs the real node binary against the stable cli.js copy, never npx", () => {
    const parsed = parseScheduledTaskXml(SAMPLE_XML);
    expect(parsed.meterProgram).toBe("C:\\Program Files\\nodejs\\node.exe");
    expect(SAMPLE_XML).not.toContain("npx");
  });

  // The negative control: if the naive shape also read as windowless, the assertion
  // above would be decoration.
  test("node started directly by the task reads back as showing a window", () => {
    const legacy = SAMPLE_XML.replace(
      /<Exec>[\s\S]*?<\/Exec>/,
      '<Exec><Command>C:\\Program Files\\nodejs\\node.exe</Command><Arguments>"C:\\Users\\dev\\.marginfront-ccc\\cli.js" run</Arguments></Exec>',
    );
    const parsed = parseScheduledTaskXml(legacy);
    expect(parsed.hidesConsoleWindow).toBe(false);
    expect(parsed.meterProgram).toBe("C:\\Program Files\\nodejs\\node.exe");
  });

  test("the console host WITHOUT --headless is not reported as windowless", () => {
    const parsed = parseScheduledTaskXml(
      SAMPLE_XML.replace("<Arguments>--headless ", "<Arguments>"),
    );
    expect(parsed.hidesConsoleWindow).toBe(false);
  });

  // Every path in the action passes through three parsers: our XML, conhost's own
  // argument splitter (which re-quotes anything with a space for CreateProcess), and
  // node's. Spaces and an ampersand are the two characters a real Windows home path
  // brings that could break one of them.
  test("a node path with spaces and a cli path with an ampersand survive the round trip", () => {
    const xml = renderScheduledTaskXml({
      nodePath: "C:\\Program Files\\nodejs\\node.exe",
      cliPath: "C:\\Users\\A & B\\.marginfront-ccc\\cli.js",
      userId: "BOX\\dev",
      consoleHostPath: "C:\\Windows\\System32\\conhost.exe",
    });
    // Escaped in the document, so schtasks accepts it...
    expect(xml).toContain(
      '--headless "C:\\Program Files\\nodejs\\node.exe" "C:\\Users\\A &amp; B\\.marginfront-ccc\\cli.js" run --log-to-files',
    );
    // ...and read back as the real characters, quoted, so a caller can compare it to
    // the path on disk.
    const parsed = parseScheduledTaskXml(xml);
    expect(parsed.hidesConsoleWindow).toBe(true);
    expect(parsed.meterProgram).toBe("C:\\Program Files\\nodejs\\node.exe");
    expect(parsed.argumentsText).toBe(
      '--headless "C:\\Program Files\\nodejs\\node.exe" "C:\\Users\\A &amp; B\\.marginfront-ccc\\cli.js" run --log-to-files'.replace(
        "&amp;",
        "&",
      ),
    );
  });

  test("the console host is named by the system root, never by PATH", () => {
    expect(defaultConsoleHostPath({ SystemRoot: "D:\\WINDOWS" })).toBe(
      "D:\\WINDOWS\\System32\\conhost.exe",
    );
    expect(defaultConsoleHostPath({ windir: "E:\\Win" })).toBe(
      "E:\\Win\\System32\\conhost.exe",
    );
    expect(defaultConsoleHostPath({})).toBe(
      "C:\\Windows\\System32\\conhost.exe",
    );
    expect(SAMPLE_XML).not.toMatch(/<Command>conhost\.exe<\/Command>/);
  });

  test("declares the encoding schtasks requires", () => {
    expect(SAMPLE_XML).toContain('encoding="UTF-16"');
  });

  test("XML-escapes a path that would otherwise break the definition", () => {
    const xml = renderScheduledTaskXml({
      nodePath: "C:\\node.exe",
      cliPath: "C:\\Users\\A & B\\cli.js",
      userId: "BOX\\a<b",
    });
    expect(xml).toContain("C:\\Users\\A &amp; B\\cli.js");
    expect(xml).toContain("BOX\\a&lt;b");
    // Still parses, which is the point of escaping in the first place, and reads back
    // as the characters that went in.
    const parsed = parseScheduledTaskXml(xml);
    expect(parsed.registered).toBe(true);
    expect(parsed.runAsUserId).toBe("BOX\\a<b");
  });
});

