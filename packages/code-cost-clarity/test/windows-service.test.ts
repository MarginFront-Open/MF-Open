// windows-service.test.ts
// ---------------------------------------------------------------------------
// WHAT THIS FILE PROVES, in two halves.
//
// HALF ONE runs everywhere: the task definition we generate says what we think it
// says, the parser reads what Windows actually returns, and the five lifecycle verbs
// issue the exact schtasks arguments they claim to. All driven through an injected
// runner, so no test here touches a real Task Scheduler.
//
// HALF TWO runs on Windows only, and it is the reason this file exists. No automated
// test can sign out and back in to prove the meter comes back. The closest honest
// substitute is: register a REAL task, then ask
// Windows what it stored, and assert on THAT. Every assertion in that half reads back
// from the system. None of them look at the XML we just wrote - a definition Windows
// silently downgraded would still match its own source text, which is exactly the
// failure a reboot would expose.
//
// BE CLEAR ABOUT WHAT THAT BUYS. It proves the task is CONFIGURED TO survive a sign-out
// and sign-in: a logon trigger for this user, restart-on-failure armed, an interactive
// per-user principal, enabled. It does NOT prove it survives. Only a real sign-out does
// that, and keeping the meter alive is its one job.
//
// HALF TWO also proves the meter gets NO CONSOLE WINDOW. That one
// runs the real action, reads the real process's window handle off the real desktop,
// and refuses to pass on a runner that cannot show windows at all. See its contract.
// ---------------------------------------------------------------------------

