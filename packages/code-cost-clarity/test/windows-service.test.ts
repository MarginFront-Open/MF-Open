describe("reading a registration back", () => {
  test("a task that does not exist", () => {
    const parsed = parseScheduledTaskXml(
      "ERROR: The system cannot find the file specified.",
    );
    expect(parsed.registered).toBe(false);
    expect(parsed.startsAtLogon).toBe(false);
    expect(parsed.perUser).toBe(false);
  });

  test("a leading BOM and blank line - how schtasks really prints it - do not confuse it", () => {
    expect(parseScheduledTaskXml("\uFEFF\r\n" + SAMPLE_XML).registered).toBe(
      true,
    );
  });

  // THE NEGATIVE CONTROLS. Each one is a definition that LOOKS installed but would not
  // do what we promised. If the parser cannot tell these apart from the real thing,
  // the survives-logon assertions are decoration.
  test("a system-account task is NOT reported as per-user", () => {
    for (const account of [
      "S-1-5-18",
      "NT AUTHORITY\\SYSTEM",
      "SYSTEM",
      "S-1-5-19",
      "S-1-5-20",
    ]) {
      const xml = SAMPLE_XML.replace(
        /<Principal id="Author">[\s\S]*?<\/Principal>/,
        `<Principal id="Author"><UserId>${account}</UserId><LogonType>ServiceAccount</LogonType><RunLevel>HighestAvailable</RunLevel></Principal>`,
      );
      expect(`${account}: ${parseScheduledTaskXml(xml).perUser}`).toBe(
        `${account}: false`,
      );
    }
  });

  test("a group-registered task is NOT reported as per-user", () => {
    const xml = SAMPLE_XML.replace(
      /<Principal id="Author">[\s\S]*?<\/Principal>/,
      '<Principal id="Author"><GroupId>BUILTIN\\Users</GroupId><UserId>BOX\\dev</UserId><LogonType>InteractiveToken</LogonType></Principal>',
    );
    expect(parseScheduledTaskXml(xml).perUser).toBe(false);
  });

  test("a stored-password principal is NOT reported as per-user", () => {
    const xml = SAMPLE_XML.replace(
      "<LogonType>InteractiveToken</LogonType>",
      "<LogonType>Password</LogonType>",
    );
    expect(parseScheduledTaskXml(xml).perUser).toBe(false);
  });

  test("a task with no restart-on-failure block is not reported as restarting", () => {
    const xml = SAMPLE_XML.replace(
      /<RestartOnFailure>[\s\S]*?<\/RestartOnFailure>/,
      "",
    );
    expect(parseScheduledTaskXml(xml).restartsOnFailure).toBe(false);
  });

  test("a time-triggered task is not reported as starting at logon", () => {
    const xml = SAMPLE_XML.replace(
      /<Triggers>[\s\S]*?<\/Triggers>/,
      "<Triggers><CalendarTrigger><StartBoundary>2026-01-01T09:00:00</StartBoundary></CalendarTrigger></Triggers>",
    );
    const parsed = parseScheduledTaskXml(xml);
    expect(parsed.startsAtLogon).toBe(false);
    expect(parsed.triggerTypes).toEqual(["CalendarTrigger"]);
  });

  // Every other case here has exactly one trigger or no logon trigger at all, so
  // without this case, dropping the "and it is the ONLY trigger" half of the
  // condition would leave the whole file green. `startsAtLogon` is not "there is a logon trigger" - it
  // is our claim that sign-in, and only sign-in, is what starts the meter. A task
  // carrying an extra trigger is a task somebody else has edited, and reporting it as
  // ours-as-registered would hide that.
  test("a logon trigger PLUS another trigger is not reported as starting at logon", () => {
    const xml = SAMPLE_XML.replace(
      "</LogonTrigger>",
      "</LogonTrigger>\n    <CalendarTrigger><StartBoundary>2026-01-01T09:00:00</StartBoundary></CalendarTrigger>",
    );
    const parsed = parseScheduledTaskXml(xml);
    // The premise: the logon trigger is still there and still enabled, so the only
    // thing that can turn this false is the extra trigger.
    expect(parsed.triggerTypes).toEqual(["LogonTrigger", "CalendarTrigger"]);
    expect(parsed.logonTriggerUserId).toBe("RUNNERBOX\\dev");
    expect(parsed.startsAtLogon).toBe(false);
  });

  test("a DISABLED logon trigger is not reported as starting at logon", () => {
    const xml = SAMPLE_XML.replace(
      "<LogonTrigger>\n      <Enabled>true</Enabled>",
      "<LogonTrigger>\n      <Enabled>false</Enabled>",
    );
    expect(parseScheduledTaskXml(xml).startsAtLogon).toBe(false);
  });

  test("a disabled task reads back disabled - the trigger alone is not enough", () => {
    // The <Enabled> inside <Settings>, not the one inside the trigger. Confusing the
    // two would report a switched-off meter as ready to go.
    const xml = SAMPLE_XML.replace(
      "<AllowStartOnDemand>true</AllowStartOnDemand>\n    <Enabled>true</Enabled>",
      "<AllowStartOnDemand>true</AllowStartOnDemand>\n    <Enabled>false</Enabled>",
    );
    const parsed = parseScheduledTaskXml(xml);
    expect(parsed.enabled).toBe(false);
    // ...and the trigger is still enabled, proving the two are read separately.
    expect(parsed.startsAtLogon).toBe(true);
  });
});

describe("decoding what schtasks writes", () => {
  test("UTF-16LE output with a byte-order mark", () => {
    const buffer = Buffer.concat([
      Buffer.from([0xff, 0xfe]),
      Buffer.from("<Task/>", "utf16le"),
    ]);
    expect(decodeSchtasksOutput(buffer)).toBe("<Task/>");
  });

  test("plain output is read as UTF-8", () => {
    expect(decodeSchtasksOutput(Buffer.from("<Task/>", "utf8"))).toBe(
      "<Task/>",
    );
  });

  test("a string passes through untouched", () => {
    expect(decodeSchtasksOutput("<Task/>")).toBe("<Task/>");
  });
});

describe("listing tasks for the orphan sweep", () => {
  // Against a REAL `schtasks /Query /FO CSV /NH` dump captured from windows-latest,
  // Windows' own tasks and all. The date and status columns are localized, which is
  // exactly why only the first column is read.
  test("pulls names out of a real task list and ignores the localized columns", () => {
    const names = parseScheduledTaskNames(
      readFileSync(CAPTURED_TASK_LIST, "utf8"),
    );
    expect(names.length).toBeGreaterThan(3);
    // Every row yielded a full task path and nothing yielded a date or a status.
    for (const name of names) {
      expect(`${name} starts with a separator: ${name.startsWith("\\")}`).toBe(
        `${name} starts with a separator: true`,
      );
    }
    expect(names).toContain("\\HostedComputeAgent");
    // And the one code-cost-clarity task the live tests registered is in there, which is what the
    // orphan sweep has to be able to find.
    expect(
      names.filter((name) => /ai\.marginfront\.ccc/.test(name)),
    ).toHaveLength(1);
  });

  test("a hand-built list separates ours from a task that merely starts the same", () => {
    const csv = [
      '"\\ai.marginfront.ccc","8/14/2026 1:00:00 PM","Ready"',
      '"\\ai.marginfront.ccc.orphan","N/A","Disabled"',
      '"\\ai.marginfront.cccother","N/A","Ready"',
      "",
    ].join("\r\n");
    expect(parseScheduledTaskNames(csv)).toEqual([
      "\\ai.marginfront.ccc",
      "\\ai.marginfront.ccc.orphan",
      "\\ai.marginfront.cccother",
    ]);
  });

  test("a failed query lists nothing rather than throwing", () => {
    expect(defaultScheduledTaskLister(() => MISSING)).toEqual([]);
  });
});

